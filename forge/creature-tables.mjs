export function valueAt(table, level, tier, fallback = "moderate") {
  const row = CREATURE_TABLES[table]?.[level];
  if (!row) throw new Error(`Нет таблицы «${table}» для уровня ${level}.`);
  return row[tier] ?? row[fallback] ?? Object.values(row)[0];
}

export function eliteHpAdjustment(level) {
  if (level <= 1) return 10;
  if (level <= 4) return 15;
  if (level <= 19) return 20;
  return 30;
}
