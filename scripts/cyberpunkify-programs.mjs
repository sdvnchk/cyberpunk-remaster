function folderPath(folderId, folderById) {
  const result = [];
  const visited = new Set();
  let currentId = folderId;
  while (currentId && folderById.has(currentId) && !visited.has(currentId)) {
    visited.add(currentId);
    const folder = folderById.get(currentId);
    result.unshift(folder.name);
    currentId = folder.folder;
  }
  return result;
}

function stripOriginalTranslation(description) {
  return description.replace(
    /<hr\b[^>]*>\s*<details>\s*<summary>Оригинал<\/summary>[\s\S]*?<\/details>\s*$/iu,
    "",
  );
}

function stripExistingProgramLead(description) {
  return description.replace(
    /^<p data-cyberpunk-program="true"><strong>Программная реализация:<\/strong>[\s\S]*?<\/p>\s*<hr>\s*/u,
    "",
  );
}

function cyberpunkifyDescription(description, flavor, itemId) {
  let result = stripExistingProgramLead(
    stripOriginalTranslation(String(description ?? "")),
  );
  for (const [pattern, replacement] of replacements) {
    // JavaScript's \b is ASCII-only even with the Unicode flag, so it does
    // not recognize Russian letters as word characters.
    const unicodePattern = new RegExp(
      pattern.source.replaceAll("\\b", ""),
      pattern.flags,
    );
    result = result.replace(unicodePattern, replacement);
  }
  for (const [pattern, replacement] of grammarReplacements) {
    result = result.replace(pattern, replacement);
  }
  for (const [pattern, replacement] of itemReplacements[itemId] ?? []) {
    result = result.replace(pattern, replacement);
  }
  return (
    `<p data-cyberpunk-program="true"><strong>Программная реализация:</strong> ` +
    `${flavor}</p><hr>${result}`
  );
}

function mechanicsSnapshot(item) {
  const clone = structuredClone(item);
  if (clone.system?.description) delete clone.system.description.value;
  if (clone.system?.traits) delete clone.system.traits.value;
  return JSON.stringify(clone);
}

const [items, folders] = await Promise.all([
  fs.readFile(itemsPath, "utf8").then(JSON.parse),
  fs.readFile(foldersPath, "utf8").then(JSON.parse),
]);
const folderById = new Map(folders.map((folder) => [folder._id, folder]));
const selected = items.filter((item) => {
  if (item.type !== "spell" || deckFocusIds.has(item._id)) return false;
  const itemPath = folderPath(item.folder, folderById);
  return itemPath[0] === "Квикхаки и Программы";
});

const selectedIds = new Set(selected.map((item) => item._id));
const missingMappings = selected
  .filter((item) => !programs[item._id])
  .map((item) => `${item._id} (${item.name})`);
const staleMappings = Object.keys(programs).filter((id) => !selectedIds.has(id));
if (missingMappings.length || staleMappings.length) {
  throw new Error(
    [
      missingMappings.length
        ? `Missing program mappings: ${missingMappings.join(", ")}`
        : "",
      staleMappings.length
        ? `Stale program mappings: ${staleMappings.join(", ")}`
        : "",
    ].filter(Boolean).join("\n"),
  );
}

for (const item of selected) {
  const before = mechanicsSnapshot(item);
  const definition = programs[item._id];
  item.system.description.value = cyberpunkifyDescription(
    item.system.description.value,
    definition.flavor,
    item._id,
  );
  const existingTraits = item.system.traits?.value ?? [];
  item.system.traits.value = [
    ...new Set([...existingTraits, "tech", ...(definition.traits ?? [])]),
  ];
  if (mechanicsSnapshot(item) !== before) {
    throw new Error(`Unexpected mechanical change to ${item.name}.`);
  }
}

